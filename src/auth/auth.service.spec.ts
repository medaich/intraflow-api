import { Test, TestingModule } from '@nestjs/testing';
import { BadRequestException, UnauthorizedException } from '@nestjs/common';
import { getRepositoryToken } from '@nestjs/typeorm';
import { ConfigService } from '@nestjs/config';
import { DataSource } from 'typeorm';
import { scrypt, randomBytes } from 'crypto';
import { promisify } from 'util';
import { AuthService } from './auth.service';
import { UsersService } from '../users/users.service';
import { User, UserRole } from '../users/entities/user.entity';
import { PasswordResetToken } from './entities/password-reset-token.entity';
import { MailService } from '../mail/mail.service';

const scryptAsync = promisify(scrypt);

describe('AuthService (Hashing, Verification & Edge Cases)', () => {
  let authService: AuthService;
  let usersService: jest.Mocked<Partial<UsersService>>;

  beforeEach(async () => {
    usersService = {
      findByEmailWithPassword: jest.fn(),
      registerWithInvite: jest.fn(),
    };

    const module: TestingModule = await Test.createTestingModule({
      providers: [
        AuthService,
        {
          provide: UsersService,
          useValue: usersService,
        },
        {
          provide: getRepositoryToken(PasswordResetToken),
          useValue: {
            findOne: jest.fn(),
            save: jest.fn(),
            update: jest.fn(),
          },
        },
        {
          provide: MailService,
          useValue: {
            sendPasswordReset: jest.fn(),
          },
        },
        {
          provide: ConfigService,
          useValue: {
            get: jest.fn().mockReturnValue(3600),
          },
        },
        {
          provide: DataSource,
          useValue: {
            transaction: jest.fn(),
          },
        },
      ],
    }).compile();

    authService = module.get<AuthService>(AuthService);
  });

  it('should be defined', () => {
    expect(authService).toBeDefined();
  });

  describe('Password Hash and Verification (v1 and v2)', () => {
    it('verifies v2 password hash generated by hashPassword()', async () => {
      const password = 'SuperSecurePassword123!';
      const hash = await authService.hashPassword(password);

      expect(hash.startsWith('v2.')).toBe(true);
      expect(await authService.verifyPassword(password, hash)).toBe(true);
      expect(await authService.verifyPassword('WrongPassword!', hash)).toBe(false);
    });

    it('verifies legacy v1 password hash (<salt>.<hash>) for backward compatibility', async () => {
      const password = 'LegacyPassword456!';
      const salt = randomBytes(8).toString('hex');
      const derivedKey = (await scryptAsync(password, salt, 32)) as Buffer;
      const v1Hash = `${salt}.${derivedKey.toString('hex')}`;

      expect(await authService.verifyPassword(password, v1Hash)).toBe(true);
      expect(await authService.verifyPassword('WrongPassword!', v1Hash)).toBe(false);
    });

    it('handles malformed stored hash safely returning false without throwing (no 500)', async () => {
      const malformedHashes = [
        'invalid_format_without_dots',
        'v2.only_two_parts',
        'v2.invalid_hex_salt!@#$.xyz',
        'v3.unsupported_version.hash',
        '',
        '..',
      ];

      for (const badHash of malformedHashes) {
        await expect(authService.verifyPassword('password', badHash)).resolves.toBe(false);
      }
    });

    it('signin throws 401 UnauthorizedException (not 500) when stored hash is malformed', async () => {
      usersService.findByEmailWithPassword!.mockResolvedValue(
        new User({
          userId: 1,
          email: 'corrupt@intraflow.dev',
          password: 'completely_corrupt_hash_not_scrypt',
          role: UserRole.EMPLOYEE,
        }),
      );

      await expect(
        authService.signin({
          email: 'corrupt@intraflow.dev',
          password: 'password123',
        }),
      ).rejects.toThrow(UnauthorizedException);
    });
  });

  describe('Dummy Hash Path for Unknown Users (Timing Equalization)', () => {
    it('executes dummy-hash verification and throws uniform 401 when email does not exist', async () => {
      usersService.findByEmailWithPassword!.mockResolvedValue(null);

      const verifySpy = jest.spyOn(authService, 'verifyPassword');

      await expect(
        authService.signin({
          email: 'nonexistent@intraflow.dev',
          password: 'AttemptPassword123!',
        }),
      ).rejects.toThrow(new UnauthorizedException('Invalid credentials'));

      expect(verifySpy).toHaveBeenCalledTimes(1);
      expect(verifySpy).toHaveBeenCalledWith(
        'AttemptPassword123!',
        expect.stringContaining('v2.0123456789abcdef0123456789abcdef'),
      );
    });
  });

  describe('forgotPassword', () => {
    it('returns uniform message without sending email when user not found', async () => {
      usersService.findByEmailWithPassword!.mockResolvedValue(null);
      const mailService = (authService as unknown as { mailService: MailService }).mailService;
      const sendSpy = jest.spyOn(mailService, 'sendPasswordReset');

      const result = await authService.forgotPassword('unknown@intraflow.dev');
      expect(result.message).toContain('If that email address is in our database');
      expect(sendSpy).not.toHaveBeenCalled();
    });

    it('creates token and sends reset email when user exists', async () => {
      usersService.findByEmailWithPassword!.mockResolvedValue(
        new User({ userId: 10, email: 'exists@intraflow.dev' }),
      );
      const mailService = (authService as unknown as { mailService: MailService }).mailService;
      const sendSpy = jest.spyOn(mailService, 'sendPasswordReset').mockResolvedValue();

      const result = await authService.forgotPassword('EXISTS@intraflow.dev ');
      expect(result.message).toContain('If that email address is in our database');
      expect(sendSpy).toHaveBeenCalledWith('exists@intraflow.dev', expect.any(String));
    });
  });

  describe('resetPassword', () => {
    it('throws BadRequestException for invalid or expired token', async () => {
      const dataSource = (authService as unknown as { dataSource: DataSource }).dataSource;
      jest.spyOn(dataSource, 'transaction').mockImplementation((cb) => {
        const mockManager = {
          getRepository: jest.fn().mockReturnValue({
            findOne: jest.fn().mockResolvedValue(null),
          }),
        };
        return cb(mockManager as never);
      });

      await expect(
        authService.resetPassword({ token: 'badtoken', password: 'NewPassword123!' }),
      ).rejects.toThrow(BadRequestException);
    });

    it('successfully resets password and updates sessionsValidFrom', async () => {
      const dataSource = (authService as unknown as { dataSource: DataSource }).dataSource;
      const mockUser = new User({ userId: 5, email: 'test@intraflow.dev' });
      const mockToken = {
        userId: 5,
        usedAt: null,
        expiresAt: new Date(Date.now() + 60000),
      };

      jest.spyOn(dataSource, 'transaction').mockImplementation((cb) => {
        const mockManager = {
          getRepository: jest.fn().mockImplementation((entity) => {
            if (entity === PasswordResetToken) {
              return {
                findOne: jest.fn().mockResolvedValue(mockToken),
                save: jest.fn().mockResolvedValue(mockToken),
              };
            }
            return {
              findOne: jest.fn().mockResolvedValue(mockUser),
              save: jest.fn().mockResolvedValue(mockUser),
            };
          }),
        };
        return cb(mockManager as never);
      });

      const res = await authService.resetPassword({
        token: 'validtoken',
        password: 'FreshPassword123!',
      });
      expect(res.message).toContain('Password has been reset');
      expect(mockToken.usedAt).toBeDefined();
      expect(mockUser.sessionsValidFrom).toBeDefined();
    });
  });
});
