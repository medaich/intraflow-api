import { Test, TestingModule } from '@nestjs/testing';
import { UnauthorizedException } from '@nestjs/common';
import { scrypt, randomBytes } from 'crypto';
import { promisify } from 'util';
import { AuthService } from './auth.service';
import { UsersService } from '../users/users.service';
import { User, UserRole } from '../users/entities/user.entity';

const scryptAsync = promisify(scrypt);

describe('AuthService (Hashing, Verification & Edge Cases)', () => {
  let authService: AuthService;
  let usersService: jest.Mocked<Partial<UsersService>>;

  beforeEach(async () => {
    usersService = {
      findByEmailWithPassword: jest.fn(),
      registerWithInvite: jest.fn(),
    };

    const module: TestingModule = await Test.createTestingModule({
      providers: [
        AuthService,
        {
          provide: UsersService,
          useValue: usersService,
        },
      ],
    }).compile();

    authService = module.get<AuthService>(AuthService);
  });

  it('should be defined', () => {
    expect(authService).toBeDefined();
  });

  describe('Password Hash and Verification (v1 and v2)', () => {
    it('verifies v2 password hash generated by hashPassword()', async () => {
      const password = 'SuperSecurePassword123!';
      const hash = await authService.hashPassword(password);

      expect(hash.startsWith('v2.')).toBe(true);
      expect(await authService.verifyPassword(password, hash)).toBe(true);
      expect(await authService.verifyPassword('WrongPassword!', hash)).toBe(false);
    });

    it('verifies legacy v1 password hash (<salt>.<hash>) for backward compatibility', async () => {
      const password = 'LegacyPassword456!';
      const salt = randomBytes(8).toString('hex');
      const derivedKey = (await scryptAsync(password, salt, 32)) as Buffer;
      const v1Hash = `${salt}.${derivedKey.toString('hex')}`;

      expect(await authService.verifyPassword(password, v1Hash)).toBe(true);
      expect(await authService.verifyPassword('WrongPassword!', v1Hash)).toBe(false);
    });

    it('handles malformed stored hash safely returning false without throwing (no 500)', async () => {
      const malformedHashes = [
        'invalid_format_without_dots',
        'v2.only_two_parts',
        'v2.invalid_hex_salt!@#$.xyz',
        'v3.unsupported_version.hash',
        '',
        '..',
      ];

      for (const badHash of malformedHashes) {
        await expect(authService.verifyPassword('password', badHash)).resolves.toBe(false);
      }
    });

    it('signin throws 401 UnauthorizedException (not 500) when stored hash is malformed', async () => {
      usersService.findByEmailWithPassword!.mockResolvedValue(
        new User({
          userId: 1,
          email: 'corrupt@intraflow.dev',
          password: 'completely_corrupt_hash_not_scrypt',
          role: UserRole.EMPLOYEE,
        }),
      );

      await expect(
        authService.signin({
          email: 'corrupt@intraflow.dev',
          password: 'password123',
        }),
      ).rejects.toThrow(UnauthorizedException);
    });
  });

  describe('Dummy Hash Path for Unknown Users (Timing Equalization)', () => {
    it('executes dummy-hash verification and throws uniform 401 when email does not exist', async () => {
      usersService.findByEmailWithPassword!.mockResolvedValue(null);

      const verifySpy = jest.spyOn(authService, 'verifyPassword');

      await expect(
        authService.signin({
          email: 'nonexistent@intraflow.dev',
          password: 'AttemptPassword123!',
        }),
      ).rejects.toThrow(new UnauthorizedException('Invalid credentials'));

      expect(verifySpy).toHaveBeenCalledTimes(1);
      expect(verifySpy).toHaveBeenCalledWith(
        'AttemptPassword123!',
        expect.stringContaining('v2.0123456789abcdef0123456789abcdef'),
      );
    });
  });
});
